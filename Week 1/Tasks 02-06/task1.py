# Task 1: Personal Information Program

# Variables Creation
name = "Swaham Patra"
age = 17
clgName = "G.P. Thane"
per = 35.5

# Print data along with data type using type()

print("Name:", name, "Data Type:", type(name))
print("Age:", age, "Data Type:", type(age))
print("College Name:", clgName, "Data Type:", type(clgName))
print("Percentage:", per, "Data Type:", type(per))

# Convert Age from integer to float.
age = float(age)
print("Age after conversion to float:", age, "Data Type:", type(age))

# Convert Percentage from float to integer.
per = int(per)
print("Percentage after conversion to integer:", per, "Data Type:", type(per))