# Task 3: Python Concepts Showcase

# Creates
# List
my_list = [15, "Swaham", 3.14, True, [1, 2, 3]]

# Tuple
my_tuple = (42, "Python", 2.718, False, (4, 5, 6))

# Dictionary
my_dict = { "name": "Swaham", "age": 17, "is_student": True, "scores": [35, 40, 36]}

# Printing the created data structures along with their types
print(f"List: {my_list} (Type: {type(my_list).__name__})")
print(f"Tuple: {my_tuple} (Type: {type(my_tuple).__name__})")
print(f"Dictionary: {my_dict} (Type: {type(my_dict).__name__})")

# {} Braces / Curly Brackets → Enclose a set or mapping/grouping of related items.
# [] Brackets / Square Brackets → Indicate indexing, selection, or an ordered collection.
# () Parentheses / Round Brackets → Indicate grouping, precedence, or function arguments.